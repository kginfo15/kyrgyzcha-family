function renderA2Check(){
  var a1=VOCAB.filter(function(w){return w.level==="A1";}).length,a2=VOCAB.length-a1;
  var seen={},tot=0,done=0;
  var rows=P46_A2.map(function(t,i){
    var ids=p46NoteIds(t[2]);
    var l=ids.filter(function(id){return cprogress[id]&&cprogress[id].status!=="new";}).length;
    var m=ids.filter(function(id){return cprogress[id]&&cprogress[id].status==="mastered";}).length;
    ids.forEach(function(id){if(seen[id])return;seen[id]=1;tot++;if(cprogress[id]&&cprogress[id].status!=="new")done++;});
    var chip=!ids.length?'<span class="p46-chip">準備中</span>':(m>=ids.length*0.8?'<span class="p46-chip ok">定着</span>':(l>0?'<span class="p46-chip mid">学習中 '+Math.round(l/ids.length*100)+'%</span>':'<span class="p46-chip">未着手</span>'));
    return '<div class="p46-row"><div class="t"><b>'+esc(t[0])+'</b><span>'+esc(t[1])+' ・ 収録 '+ids.length+'文</span></div>'+chip+
      (ids.length?'<button type="button" class="btn" style="padding:6px 10px;font-size:12px" data-act="p46a2" data-val="'+i+'">練習</button>':'')+'</div>';
  }).join("");
  var h='<div class="card" style="padding:14px;margin-bottom:12px"><b>収録データ</b>'+
    '<div class="small muted" style="margin-top:6px;line-height:1.7">単語 '+VOCAB.length+'語（A1 '+a1+'／A2 '+a2+'）・瞬間作文 '+COMPOSE.length+'文・文法ユニット '+UNITS.length+'<br>A2の文法項目 '+P46_A2.length+'件すべてに練習文があります。学習済み '+done+'／'+tot+'文。</div></div>';
  h+='<div class="card" style="padding:4px 14px">'+rows+'</div>';
  h+='<div class="note" style="margin-top:12px">目安：A2 は ТБУ（基礎レベル・ТРКИ-1の一つ手前）相当。「定着」は練習文の8割以上がマスター状態。教材はネイティブ確認前の draft を含みます。</div>';
  return h;
}
