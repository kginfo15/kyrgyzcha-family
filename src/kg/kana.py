def kana_word(w):
    w=w.lower().replace('ь','').replace('ъ','');out=[];i=0;n=len(w)
    while i<n:
        c=w[i]
        if c in V:
            v=V[c];k=ALONE[v]
            if i+1<n and w[i+1]==c: k+='ー';i+=1
            out.append(k);i+=1
        elif c in T:
            if i+1<n and w[i+1] in V:
                v=V[w[i+1]];k=T[c][v];j=i+2
                if j<n and w[j]==w[i+1]: k+='ー';j+=1
                out.append(k);i=j
            else:
                k=T[c]['']
                out.append(k);i+=1
        else: out.append(c);i+=1
    return ''.join(out)
def kana(t):
    import re
    return ' '.join('・'.join(kana_word(y) for y in x.split('-') if y) for x in t.split(' ') if x)
